-- RESTAURANT MANAGEMENT SYSTEM DATABASE
-- Run in Supabase Dashboard > SQL Editor.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default 'Restaurant User',
  email text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  description text default '',
  price numeric(12,2) not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  low_stock_level integer not null default 5 check (low_stock_level >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  total numeric(12,2) not null default 0 check (total >= 0),
  status text not null default 'completed'
    check (status in ('completed','cancelled')),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  menu_item_id bigint not null references public.menu_items(id),
  item_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  subtotal numeric(12,2) not null check (subtotal >= 0)
);

-- Automatically create a profile after registration.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, email)
  values (
    new.id,
    coalesce(
      new.raw_user_meta_data ->> 'full_name',
      new.raw_user_meta_data ->> 'name',
      split_part(new.email, '@', 1)
    ),
    coalesce(new.email, '')
  )
  on conflict (id) do update
  set email = excluded.email;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
after insert on auth.users
for each row
execute procedure public.handle_new_user();

-- Enable row-level security.
alter table public.profiles enable row level security;
alter table public.menu_items enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- Profile policies.
drop policy if exists "Users can read own profile" on public.profiles;

create policy "Users can read own profile"
on public.profiles
for select
to authenticated
using (id = (select auth.uid()));

drop policy if exists "Users can update own profile" on public.profiles;

create policy "Users can update own profile"
on public.profiles
for update
to authenticated
using (id = (select auth.uid()))
with check (id = (select auth.uid()));

-- Menu policies: authenticated restaurant staff share menu data.
drop policy if exists "Authenticated users can read menu" on public.menu_items;

create policy "Authenticated users can read menu"
on public.menu_items
for select
to authenticated
using (true);

drop policy if exists "Authenticated users can add menu" on public.menu_items;

create policy "Authenticated users can add menu"
on public.menu_items
for insert
to authenticated
with check (true);

drop policy if exists "Authenticated users can update menu" on public.menu_items;

create policy "Authenticated users can update menu"
on public.menu_items
for update
to authenticated
using (true)
with check (true);

drop policy if exists "Authenticated users can delete menu" on public.menu_items;

create policy "Authenticated users can delete menu"
on public.menu_items
for delete
to authenticated
using (true);

-- Order policies.
drop policy if exists "Authenticated users can read orders" on public.orders;

create policy "Authenticated users can read orders"
on public.orders
for select
to authenticated
using (true);

drop policy if exists "Authenticated users can read order items" on public.order_items;

create policy "Authenticated users can read order items"
on public.order_items
for select
to authenticated
using (true);

drop policy if exists "Authenticated users can create orders for themselves" on public.orders;

create policy "Authenticated users can create orders for themselves"
on public.orders
for insert
to authenticated
with check (created_by = (select auth.uid()));

drop policy if exists "Authenticated users can add order items to own orders" on public.order_items;

create policy "Authenticated users can add order items to own orders"
on public.order_items
for insert
to authenticated
with check (
  exists (
    select 1
    from public.orders
    where orders.id = order_items.order_id
    and orders.created_by = (select auth.uid())
  )
);

-- Record a sale and deduct stock in one database transaction.
create or replace function public.create_order(
  p_item_id bigint,
  p_quantity integer
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_item public.menu_items%rowtype;
  v_order_id bigint;
  v_subtotal numeric(12,2);
begin
  if auth.uid() is null then
    raise exception 'You must be signed in.';
  end if;

  if p_quantity is null or p_quantity < 1 then
    raise exception 'Quantity must be at least 1.';
  end if;

  select *
  into v_item
  from public.menu_items
  where id = p_item_id
  for update;

  if not found then
    raise exception 'Menu item was not found.';
  end if;

  if v_item.stock < p_quantity then
    raise exception 'Not enough stock available.';
  end if;

  v_subtotal := v_item.price * p_quantity;

  insert into public.orders(total, created_by)
  values (v_subtotal, auth.uid())
  returning id into v_order_id;

  insert into public.order_items(
    order_id,
    menu_item_id,
    item_name,
    quantity,
    unit_price,
    subtotal
  )
  values (
    v_order_id,
    v_item.id,
    v_item.name,
    p_quantity,
    v_item.price,
    v_subtotal
  );

  update public.menu_items
  set
    stock = stock - p_quantity,
    updated_at = now()
  where id = v_item.id;

  return v_order_id;
end;
$$;

grant execute on function public.create_order(bigint, integer)
to authenticated;
